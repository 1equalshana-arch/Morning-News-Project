import feedparser
import asyncio
import schedule
import time
from telegram import Bot
from datetime import datetime
import urllib.parse
import sys

# --- 설정 구간 ---
TELEGRAM_TOKEN = '8538184853:AAG8VzdubYAIzwl6KXbStRAOeCg9c1kG6nQ'
CHAT_ID = '8283045381'
TICKERS = ["NVDA", "TSLA", "AAPL", "MSFT", "AMD", "META", "GOOGL"]
# ------------------

async def get_google_news(ticker):
    """구글 뉴스 RSS 사용"""
    try:
        encoded_ticker = urllib.parse.quote(f"{ticker} stock")
        url = f"https://news.google.com/rss/search?q={encoded_ticker}&hl=en-US&gl=US&ceid=US:en"
        feed = feedparser.parse(url)
        news_items = []
        for entry in feed.entries[:3]:
            news_items.append(f"🔥 [{ticker}] {entry.title}\n🔗 {entry.link}")
        return news_items if news_items else [f"ℹ️ [{ticker}] 최근 뉴스가 없습니다."]
    except Exception as e:
        return [f"❌ {ticker} 뉴스 조회 실패: {str(e)}"]

async def send_daily_report():
    """실제로 텔레그램 메시지를 전송하는 핵심 함수"""
    print("📢 텔레그램으로 뉴스 전송을 시작합니다...")
    try:
        bot = Bot(token=TELEGRAM_TOKEN)
        today = datetime.now().strftime("%Y-%m-%d")

        # 헤더 전송
        await bot.send_message(chat_id=CHAT_ID, text=f"📊 [{today}] 종목별 핵심 뉴스\n" + "="*20)

        for ticker in TICKERS:
            news_items = await get_google_news(ticker)
            message = "\n\n".join(news_items)
            await bot.send_message(chat_id=CHAT_ID, text=message)
            print(f"✅ {ticker} 전송 완료")
            await asyncio.sleep(1) # 차단 방지

        print("🏁 모든 종목 전송이 완료되었습니다!")
    except Exception as e:
        print(f"❌ 전송 중 에러 발생: {e}")

# --- 실행 로직 ---

# 1. 즉시 테스트 실행을 위한 헬퍼
def run_now():
    print(f"[{datetime.now()}] 즉시 테스트 전송 시도...")
    loop = asyncio.get_event_loop()
    if loop.is_running():
        # 주피터/코랩 환경
        loop.create_task(send_daily_report())
    else:
        # 일반 파이썬 환경
        loop.run_until_complete(send_daily_report())

# 2. 스케줄러용 함수
def scheduled_job():
    run_now()

# 실행 즉시 테스트 메시지 발송
run_now()

# 매일 오전 09:00 예약
schedule.every().day.at("09:00").do(scheduled_job)

